#!/usr/bin/env python3
"""Run a GROUP of single-GPU pokec_gated_lm cells inside ONE whole-node
HTCondor job, one process per GPU.

Why (2026-08-26): the H100 pool vanished from the cluster and the only
free >=80 GB GPUs (g181-g184, 8x A100-SXM4-80GB each) carry a START policy
that admits WHOLE-NODE jobs only (RequestCpus == TotalCpus && RequestMemory
== TotalMemory && RequestGpus == TotalGpus && RequestDisk == TotalDisk).
Our cells need one GPU each, so a node job packs up to eight of them.

Every cell is launched EXACTLY as its ordinary single-GPU Condor job would
be: the per-cell environment and positional arguments are rebuilt from the
cell's own generated sub file (its `environment = "..."` and `arguments =`
lines, with $(col) substituted from the cell's row in its configs file) and
the same idempotent wrapper is executed, so artifacts, configs and logs are
byte-for-byte what the 1-GPU path would produce; only CUDA_VISIBLE_DEVICES
(one assigned GPU) and the thread caps differ. stdout/stderr of each cell go
to experiments/condor/logs/<tag>.out/.err like the single-job layout.

Usage:
  node_pack.py MANIFEST.json GROUP_ID [--dry-run] [--repo DIR]
The manifest (generated by gen_pofd_sweep.py) maps group ids to lists of
{"tag", "configs", "sub"} entries (paths relative to the repo root).

Exit code: the number of cells that exited non-zero (0 == all succeeded),
so on_exit_hold/periodic_release retry the node job and the idempotent
wrapper skips every cell that already completed.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import subprocess
import sys
import time
from pathlib import Path

MAX_PER_NODE = 8
THREADS_PER_CELL = 16          # 128 cores / 8 GPUs


def parse_sub(sub_text: str):
    """(executable, arguments_template, environment_template, queue_cols)
    from a generated single-GPU sub file."""
    exe = args = env = None
    cols = None
    for line in sub_text.splitlines():
        s = line.strip()
        if s.startswith("#") or not s:
            continue
        if s.startswith("executable"):
            exe = s.split("=", 1)[1].strip()
        elif s.startswith("arguments"):
            args = s.split("=", 1)[1].strip()
        elif s.startswith("environment"):
            env = s.split("=", 1)[1].strip()
            if env.startswith('"') and env.endswith('"'):
                env = env[1:-1]
        elif s.startswith("queue"):
            m = re.match(r"queue\s+(.*?)\s+from\s+(\S+)", s)
            if not m:
                raise ValueError(f"unsupported queue line: {s}")
            cols = [c.strip() for c in m.group(1).split(",")]
    if not (exe and args is not None and env is not None and cols):
        raise ValueError("sub file lacks executable/arguments/environment/queue")
    return exe, args, env, cols


def find_row(configs_text: str, tag: str, cols):
    for line in configs_text.splitlines():
        if not line.strip():
            continue
        vals = [v.strip() for v in line.split(",")]
        if vals[0] == tag:
            if len(vals) != len(cols):
                raise ValueError(f"{tag}: row has {len(vals)} columns, the "
                                 f"sub's queue line names {len(cols)}")
            return dict(zip(cols, vals))
    raise KeyError(f"tag {tag} not found in configs")


_SUBST = re.compile(r"\$\((\w+)\)")


def substitute(template: str, row: dict):
    def rep(m):
        k = m.group(1)
        if k not in row:
            raise KeyError(f"$({k}) has no column in the configs row")
        return row[k]
    return _SUBST.sub(rep, template)


def build_cell(entry: dict, repo: Path):
    """The exact (executable, argv, env_dict) the single-GPU job would run."""
    sub_text = (repo / entry["sub"]).read_text()
    cfg_text = (repo / entry["configs"]).read_text()
    exe, args_t, env_t, cols = parse_sub(sub_text)
    row = find_row(cfg_text, entry["tag"], cols)
    argv = shlex.split(substitute(args_t, row))
    env = {}
    for tok in shlex.split(substitute(env_t, row)):
        k, _, v = tok.partition("=")
        env[k] = v
    return exe, argv, env, row


def assigned_gpus(n: int):
    """One GPU id per cell: Condor exposes the node's assignment through
    CUDA_VISIBLE_DEVICES (indices or GPU-<uuid> names); fall back to 0..n-1."""
    raw = os.environ.get("CUDA_VISIBLE_DEVICES", "").strip()
    ids = [x.strip() for x in raw.split(",") if x.strip()] if raw else []
    if len(ids) < n:
        ids = [str(i) for i in range(n)]
    return ids[:n]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("manifest")
    ap.add_argument("group")
    ap.add_argument("--repo", default=os.environ.get("REPO", "."))
    ap.add_argument("--dry-run", action="store_true",
                    help="print what would run; launch nothing")
    a = ap.parse_args()
    repo = Path(a.repo).resolve()
    man = json.loads((repo / a.manifest).read_text()
                     if not Path(a.manifest).is_absolute()
                     else Path(a.manifest).read_text())
    groups = man["groups"]
    if a.group not in groups:
        print(f"[node_pack] group {a.group!r} not in manifest "
              f"({sorted(groups)})", file=sys.stderr)
        return 2
    entries = groups[a.group]
    if not 1 <= len(entries) <= MAX_PER_NODE:
        print(f"[node_pack] group {a.group} has {len(entries)} cells; "
              f"1..{MAX_PER_NODE} allowed", file=sys.stderr)
        return 2
    gpus = assigned_gpus(len(entries))
    logs = repo / "experiments" / "condor" / "logs"
    logs.mkdir(parents=True, exist_ok=True)
    print(f"[node_pack] group {a.group}: {len(entries)} cell(s) on "
          f"{os.uname().nodename}; GPUs {gpus}", flush=True)

    procs = []
    for i, entry in enumerate(entries):
        exe, argv, env, row = build_cell(entry, repo)
        tag = entry["tag"]
        cell_env = dict(os.environ)
        cell_env.update(env)
        cell_env["CUDA_VISIBLE_DEVICES"] = gpus[i]
        cell_env["OMP_NUM_THREADS"] = str(THREADS_PER_CELL)
        cell_env["MKL_NUM_THREADS"] = str(THREADS_PER_CELL)
        cell_env["NODE_PACK_GROUP"] = a.group
        cmd = [exe] + argv
        print(f"[node_pack]   [{i}] gpu={gpus[i]} {tag}: {exe} "
              f"{' '.join(argv[:4])} ... ({len(env)} env vars)", flush=True)
        if a.dry_run:
            continue
        out = open(logs / f"{tag}.out", "a")
        err = open(logs / f"{tag}.err", "a")
        out.write(f"\n[node_pack] {time.strftime('%F %T')} start on "
                  f"{os.uname().nodename} gpu={gpus[i]} group={a.group}\n")
        out.flush()
        p = subprocess.Popen(cmd, env=cell_env, stdout=out, stderr=err,
                             cwd=str(repo))
        procs.append((tag, p, out, err, time.time()))
    if a.dry_run:
        print("[node_pack] dry run: nothing launched")
        return 0

    failures = 0
    pending = list(procs)
    while pending:
        time.sleep(30)
        still = []
        for tag, p, out, err, t0 in pending:
            rc = p.poll()
            if rc is None:
                still.append((tag, p, out, err, t0))
                continue
            dt = (time.time() - t0) / 60.0
            out.write(f"[node_pack] {time.strftime('%F %T')} exit {rc} "
                      f"after {dt:.1f} min\n")
            out.close(); err.close()
            print(f"[node_pack] {tag}: exit {rc} after {dt:.1f} min",
                  flush=True)
            if rc != 0:
                failures += 1
        pending = still
    print(f"[node_pack] group {a.group} done: {len(procs) - failures} ok, "
          f"{failures} failed", flush=True)
    return failures


if __name__ == "__main__":
    sys.exit(main())
